  static String docxDoc(String text) {
    final p = text.split('\n').map((l) =>
      '<w:p><w:r><w:t xml:space="preserve">$l</w:t></w:r></w:p>').join();
    return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
      '<w:document xmlns:w="http://schemas.openxmlformats.org/wordprocessingml/2006/main">'
      '<w:body>$p</w:body></w:document>';
  }

