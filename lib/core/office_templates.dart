  static String xlsxSs(List<String> texts) {
    final items = texts.map((t) => '<si><t xml:space="preserve">${escXml(t)}</t></si>').join();
    return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
      '<sst xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
      'count="${texts.length}" uniqueCount="${texts.length}">$items</sst>';
  }

  static String xlsxSheet(List<String> rows, String Function(int) col) {
    final b = StringBuffer();
    for (int r = 0; r < rows.length; r++) {
      final cols = rows[r].split('\t');
      final c = StringBuffer();
      for (int i = 0; i < cols.length; i++) {
        c.write('<c r="${col(i)}${r + 1}" t="s"><v>$r</v></c>');
      }
      b.write('<row r="${r + 1}">$c</row>');
    }
    return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
      '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"'
      'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
      '<sheetData>$b</sheetData></worksheet>';
  }

