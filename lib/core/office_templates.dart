  static String pptxSlide(int num, String text) {
    final lines = text.split('\n');
    final shapes = StringBuffer();
    double y = 254000;
    for (final line in lines) {
      if (line.trim().isEmpty) { y += 300000; continue; }
      shapes.write(
        '<p:sp><p:nvSpPr><p:cNvPr id="${shapes.length + 1}" name=""/>'
        '<p:cNvSpPr txBox="1"/><p:nvPr/></p:nvSpPr>'
        '<p:spPr><a:xfrm><a:off x="600000" y="${y.toInt()}"/>'
        '<a:ext cx="8000000" cy="400000"/></a:xfrm></p:spPr>'
        '<p:txBody><a:bodyPr/><a:lstStyle/><a:p><a:r><a:rPr lang="es-MX" sz="1800"/>'
        '<a:t>${escXml(line)}</a:t></a:r></a:p></p:txBody></p:sp>');
      y += 400000;
    }
    return '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
      '<p:sld xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main"'
      'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"'
      'xmlns:p="http://schemas.openxmlformats.org/presentationml/2006/main">'
      '<p:cSld><p:spTree><p:nvGrpSpPr><p:cNvPr id="1" name=""/><p:cNvGrpSpPr/><p:nvPr/></p:nvGrpSpPr>'
      '<p:grpSpPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="0" cy="0"/><a:chOff x="0" y="0"/><a:chExt cx="0" cy="0"/></a:xfrm></p:grpSpPr>$shapes</p:spTree></p:cSld>'
      '</p:sld>';
  }

